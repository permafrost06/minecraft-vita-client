#!/usr/bin/env python3
"""Generate compact, deduplicated Java 1.19.4 collision shapes (minecraft-data, MIT)."""
import hashlib,json,sys,urllib.request
from pathlib import Path
BASE='https://raw.githubusercontent.com/PrismarineJS/minecraft-data/master/data/pc/1.19.4/'
def read(i,name):
    return Path(sys.argv[i]).read_bytes() if len(sys.argv)>i else urllib.request.urlopen(BASE+name,timeout=30).read()
braw=read(1,'blocks.json');sraw=read(2,'blockCollisionShapes.json')
blocks=json.loads(braw);source=json.loads(sraw)
unique=[];lookup={};ids={};boxes=[];offsets=[]
for key,shape in sorted(source['shapes'].items(),key=lambda x:int(x[0])):
    normalized=tuple(tuple(round(v*32) for v in b) for b in shape)
    assert all(abs(v*32-round(v*32))<1e-6 for b in shape for v in b)
    if normalized not in lookup:
        lookup[normalized]=len(unique);unique.append(normalized)
    ids[int(key)]=lookup[normalized]
state=[ids[1]]*(max(b['maxStateId'] for b in blocks)+1)
for b in blocks:
    shapes=source['blocks'][b['name']]
    if isinstance(shapes,int):shapes=[shapes]*(b['maxStateId']-b['minStateId']+1)
    assert len(shapes)==b['maxStateId']-b['minStateId']+1
    for n,s in enumerate(shapes):state[b['minStateId']+n]=ids[s]
for shape in unique:
    offsets.append((len(boxes),len(shape)));boxes.extend(shape)
lines=['/* Generated by tools/collisions.py; minecraft-data MIT, see vendor/MINECRAFT-DATA-LICENSE. */',f'/* blocks SHA256 {hashlib.sha256(braw).hexdigest()} */',f'/* shapes SHA256 {hashlib.sha256(sraw).hexdigest()} */','static const McBlockBox block_boxes[] = {']
lines += ['{{'+','.join(map(str,b))+'}},' for b in boxes]
lines += ['};','static const McShape shapes[] = {']+['{'+str(o)+','+str(n)+'},' for o,n in offsets]+['};','static const uint16_t state_shapes[] = {']
lines += [','.join(map(str,state[i:i+24]))+',' for i in range(0,len(state),24)]
lines += ['};',f'#define MC_FALLBACK_SHAPE {ids[1]}']
Path('src/collision_data.inc').write_text('\n'.join(lines)+'\n')
print(len(unique),'deduplicated shapes,',len(boxes),'boxes,',len(state),'states')
