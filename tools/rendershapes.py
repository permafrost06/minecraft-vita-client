#!/usr/bin/env python3
"""Generate render/target boxes for Java 1.19.4 blocks that have no collision shape.

Block names and state layouts come from PrismarineJS minecraft-data (MIT). The boxes
are original approximations of vanilla outlines in 1/16 block units, derived from
each state's properties. Usage: python tools/rendershapes.py [blocks.json]
"""
import hashlib, json, sys, urllib.request
from pathlib import Path

BASE = 'https://raw.githubusercontent.com/PrismarineJS/minecraft-data/master/data/pc/1.19.4/'
raw = Path(sys.argv[1]).read_bytes() if len(sys.argv) > 1 else urllib.request.urlopen(BASE + 'blocks.json', timeout=30).read()
blocks = json.loads(raw)

def rotate(box, facing):
    """Rotate a box authored for facing=north (attached to the south side) about the block centre."""
    x0, y0, z0, x1, y1, z1 = box
    if facing == 'north': return box
    if facing == 'south': return (16 - x1, y0, 16 - z1, 16 - x0, y1, 16 - z0)
    if facing == 'west': return (z0, y0, 16 - x1, z1, y1, 16 - x0)
    if facing == 'east': return (16 - z1, y0, x0, 16 - z0, y1, x1)
    raise ValueError(facing)

def states(b):
    """Yield (state id, {property: value}) with the last property varying fastest; booleans are true first."""
    props = b['states']
    values = [p.get('values') or ['true', 'false'] for p in props]
    total = 1
    for v in values: total *= len(v)
    for index in range(total):
        rest, chosen = index, {}
        for p, v in reversed(list(zip(props, values))):
            chosen[p['name']] = v[rest % len(v)]; rest //= len(v)
        yield b['minStateId'] + index, chosen

FACES = {'north': (0, 0, 0, 16, 16, 1), 'south': (0, 0, 15, 16, 16, 16), 'west': (0, 0, 0, 1, 16, 16),
         'east': (15, 0, 0, 16, 16, 16), 'up': (0, 15, 0, 16, 16, 16), 'down': (0, 0, 0, 16, 1, 16)}

def shape(name, s):
    facing = s.get('facing')
    if name.endswith('wall_torch'):
        return [rotate((6.5, 3, 11, 9.5, 13, 16), facing)]
    if name.endswith('_button'):
        depth = 1 if s['powered'] == 'true' else 2
        if s['face'] == 'wall': return [rotate((5, 6, 16 - depth, 11, 10, 16), facing)]
        y0, y1 = (0, depth) if s['face'] == 'floor' else (16 - depth, 16)
        return [(5, y0, 6, 11, y1, 10) if facing in ('north', 'south') else (6, y0, 5, 10, y1, 11)]
    if name == 'lever':
        if s['face'] == 'wall': return [rotate((5, 4, 13, 11, 12, 16), facing), rotate((7, 7, 6, 9, 9, 13), facing)]
        base = (5, 0, 4, 11, 3, 12) if facing in ('north', 'south') else (4, 0, 5, 12, 3, 11)
        if s['face'] == 'floor': return [base, (7, 3, 7, 9, 10, 9)]
        return [(base[0], 13, base[2], base[3], 16, base[5]), (7, 6, 7, 9, 13, 9)]
    if name in ('vine', 'glow_lichen', 'sculk_vein'):
        return [FACES[f] for f in ('north', 'south', 'west', 'east', 'up', 'down') if s.get(f) == 'true']
    if name == 'piston_head':
        return None
    if name.endswith('_wall_skull') or name.endswith('_wall_head'):
        return [rotate((4, 4, 8, 12, 12, 16), facing)]
    if name.endswith('_skull') or name.endswith('_head'):
        return [(3, 0, 3, 13, 8, 13) if name.startswith('piglin') else (4, 0, 4, 12, 8, 12)]
    if name.endswith('coral_wall_fan'):
        return [rotate((1, 6, 6, 15, 8, 16), facing)]
    if name == 'sea_pickle':
        spots = [(6, 6), (3, 9), (9, 4), (9, 10)][:int(s['pickles'])]
        return [(x, 0, z, x + 3, 6, z + 3) for x, z in spots]
    if name == 'tripwire_hook':
        return [rotate((6, 1, 14, 10, 9, 16), facing), rotate((7, 4, 9, 9, 6, 14), facing)]
    return None

entries, unique, lookup, boxes, offsets = [], [], {}, [], []
for b in blocks:
    for state, props in states(b):
        boxes_16 = shape(b['name'], props)
        if boxes_16 is None: continue
        key = tuple(tuple(int(round(v * 2)) for v in box) for box in boxes_16)
        if key not in lookup:
            lookup[key] = len(unique); unique.append(key)
        entries.append((state, lookup[key]))
for s in unique:
    offsets.append((len(boxes), len(s))); boxes.extend(s)
lines = ['/* Generated by tools/rendershapes.py; block layouts: minecraft-data MIT, see vendor/MINECRAFT-DATA-LICENSE.',
         '   Boxes are original outline approximations in 1/32 block units. */',
         f'/* blocks SHA256 {hashlib.sha256(raw).hexdigest()} */',
         'static const McBlockBox render_boxes[] = {'] + ['{{' + ','.join(map(str, b)) + '}},' for b in boxes] + ['};']
lines += ['static const McShape render_shapes[] = {'] + [f'{{{o},{n}}},' for o, n in offsets] + ['};']
lines += ['/* Sorted (state, shape) pairs. */', 'static const uint16_t render_states[][2] = {']
lines += [f'{{{s},{i}}},' for s, i in sorted(entries)] + ['};']
Path('src/render_shapes.inc').write_text('\n'.join(lines) + '\n')
print(len(entries), 'states,', len(unique), 'shapes,', len(boxes), 'boxes')
