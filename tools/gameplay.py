#!/usr/bin/env python3
"""Generate 1.19.4 hardness, harvest tools, tool speeds and item-use durations."""
import hashlib,json,sys,urllib.request
from pathlib import Path
base='https://raw.githubusercontent.com/PrismarineJS/minecraft-data/master/data/pc/1.19.4/'
def read(i,name):return Path(sys.argv[i]).read_bytes() if len(sys.argv)>i else urllib.request.urlopen(base+name,timeout=30).read()
braw=read(1,'blocks.json');mraw=read(2,'materials.json');fraw=read(3,'foods.json');iraw=read(4,'items.json')
blocks=json.loads(braw);materials=json.loads(mraw);foods={f['id'] for f in json.loads(fraw)};items=json.loads(iraw)
lines=['/* Generated by tools/gameplay.py; minecraft-data MIT, see vendor/MINECRAFT-DATA-LICENSE. */']
for name,data in [('blocks',braw),('materials',mraw),('foods',fraw),('items',iraw)]:lines.append('/* '+name+' SHA256 '+hashlib.sha256(data).hexdigest()+' */')
lines.append('static const McToolSpeed tool_speeds[] = {')
matranges={};offset=0
for name,tools in materials.items():
 matranges[name]=(offset,len(tools))
 for item,speed in tools.items():lines.append('{%s,%sf},'%(item,float(speed)));offset+=1
lines.append('};');lines.append('static const uint16_t harvest_tools[] = {')
alltools=[]
for b in blocks:alltools.extend(int(t) for t,v in b.get('harvestTools',{}).items() if v)
lines.append(','.join(map(str,alltools)) or '0');lines.append('};');lines.append('static const McDigDef dig_defs[] = {');offset=0
interactive={'crafting_table','furnace','blast_furnace','smoker','anvil','chipped_anvil','damaged_anvil','grindstone','smithing_table','cartography_table','stonecutter','enchanting_table','brewing_stand','beacon','loom','hopper','dispenser','dropper','lever','bell','note_block','jukebox','composter','respawn_anchor','lectern','cake'}
for b in blocks:
 start,count=matranges.get(b.get('material','default'),(0,0));tools=[t for t,v in b.get('harvestTools',{}).items() if v];name=b['name'];inter=name in interactive or name.endswith(('_chest','chest','_door','_trapdoor','_fence_gate','_button','_bed','_shulker_box'))
 lines.append('{%d,%d,%sf,%d,%d,%d,%d,%d,%d,%s},'%(b['minStateId'],b['maxStateId'],float(b['hardness'] or 0),start,count,offset,len(tools),int(b['diggable']),int(inter),json.dumps(name)))
 offset+=len(tools)
lines.append('};');lines.append('static const McUseDef use_defs[] = {')
for i in items:
 n=i['name'];ticks=16 if n=='dried_kelp' else 40 if n=='honey_bottle' else 32 if i['id'] in foods or n.endswith('potion') or n=='milk_bucket' else 72000 if n in {'bow','crossbow','trident','shield','spyglass'} else 0
 always=n in {'golden_apple','enchanted_golden_apple','chorus_fruit','honey_bottle'}
 lines.append('{%d,%d,%d},'%(ticks,int(i['id'] in foods),int(always)))
lines.append('};');Path('src/gameplay_data.inc').write_text('\n'.join(lines)+'\n')
