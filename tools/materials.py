#!/usr/bin/env python3
"""Generate state-ID colors from minecraft-data; colors are original approximations."""
import hashlib,json,urllib.request
from pathlib import Path
URL='https://raw.githubusercontent.com/PrismarineJS/minecraft-data/master/data/pc/1.19.4/blocks.json'
# Use a local downloaded copy when supplied; the generated table is checked in.
import sys
raw=Path(sys.argv[1]).read_bytes() if len(sys.argv)>1 else urllib.request.urlopen(URL,timeout=30).read()
blocks=json.loads(raw)
lines=['/* Generated by tools/materials.py. minecraft-data (MIT); see vendor/MINECRAFT-DATA-LICENSE. */',f'/* Input SHA-256: {hashlib.sha256(raw).hexdigest()} */']
for b in blocks:
 n=b['name']; c=0x85858a; top=None; style=1
 if b['boundingBox']=='empty':style=0
 if 'stone' in n or 'ore' in n or n in ('bedrock','gravel','andesite','tuff'):c=0x82858a
 if 'dirt' in n or 'mud' in n or 'podzol' in n:c=0x805537
 if n=='grass_block':c=0x805537;top=0x71a542
 if 'sand' in n:c=0xd9cb8c
 if 'red_sand' in n:c=0xb66e3b
 if 'snow' in n or 'quartz' in n or 'white' in n:c=0xe5ebee
 if 'deepslate' in n or 'blackstone' in n or n=='basalt':c=0x43464e
 if 'netherrack' in n:c=0x884739
 if 'end_stone' in n:c=0xd3d3a0
 if 'planks' in n or 'wood' in n:c=0xa17e47
 if 'spruce' in n:c=0x75512f
 if 'log' in n or 'stem' in n:c=0x715031;top=0xa27f4b
 if 'birch_log' in n:c=0xd7d3be;top=0xb49d6f
 if 'leaves' in n or 'moss' in n:c=0x477f35
 if 'azalea' in n:c=0x4d863f
 if 'ice' in n:c=0x8bbcd9
 if n=='water':c=0x3f79b6;style=2
 if n=='lava':c=0xef771b;style=3
 if 'glass' in n:c=0xb9d9dd
 if 'cobblestone' in n:c=0x757e77
 if 'coal' in n:c=0x44444b
 if 'gold' in n:c=0xc7a743
 if 'copper' in n:c=0xb17850
 if n in ('air','cave_air','void_air','barrier','light','structure_void'):style=0
 if top is None:top=c
 lines.append(f'{{{b["minStateId"]},{b["maxStateId"]},0x{c:06x},0x{top:06x},{style}}}, /* {n} */')
Path('src/materials.inc').write_text('\n'.join(lines)+'\n')
print('Generated',len(blocks),'block-state ranges')
