#!/usr/bin/env python3
"""Generate Java 1.19.4 entity dimensions and metadata indices (minecraft-data, MIT)."""
import hashlib,json,sys,urllib.request
from pathlib import Path
url='https://raw.githubusercontent.com/PrismarineJS/minecraft-data/master/data/pc/1.19.4/entities.json'
raw=Path(sys.argv[1]).read_bytes() if len(sys.argv)>1 else urllib.request.urlopen(url,timeout=30).read()
humanoids={'player','zombie','husk','drowned','zombie_villager','skeleton','stray','wither_skeleton','piglin','piglin_brute','zombified_piglin','villager','wandering_trader','witch','pillager','vindicator','evoker','illusioner','enderman','iron_golem','snow_golem','armor_stand'}
lines=['/* Generated by tools/entities.py; minecraft-data MIT, see vendor/MINECRAFT-DATA-LICENSE. */','/* source SHA256 '+hashlib.sha256(raw).hexdigest()+' */','static const McEntityDef entity_defs[] = {']
for e in json.loads(raw):
 keys=e['metadataKeys'];kind=1 if e['name'] in humanoids else 2 if e['type']=='animal' or e['name'] in {'creeper','spider','cave_spider','ravager'} else 3 if e['name']=='item' else 4 if e['name']=='experience_orb' else 0
 idx=lambda key:keys.index(key) if key in keys else -1
 color=0x506040 | (int(hashlib.sha256(e['name'].encode()).hexdigest()[:6],16)&0x9f9f9f)
 lines.append('{%d,"%s",%sf,%sf,%d,%d,%d,%d,0x%06x},'%(e['id'],e['displayName'],float(e['width']),float(e['height']),kind,idx('baby'),idx('item'),idx('health'),color))
lines.append('};')
Path('src/entity_data.inc').write_text('\n'.join(lines)+'\n')
