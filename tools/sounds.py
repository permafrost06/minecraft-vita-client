#!/usr/bin/env python3
"""Generate sound identifier lookup from a vanilla 1.19.4 registry report.
java -DbundlerMainClass=net.minecraft.data.Main -jar server.jar --reports --output REPORT_DIR
python tools/sounds.py REPORT_DIR/reports/registries.json
Only identifier names/IDs are retained; no audio assets are copied.
"""
import hashlib, json, sys
from pathlib import Path
raw = Path(sys.argv[1]).read_bytes()
entries = json.loads(raw)['minecraft:sound_event']['entries']
names = [''] * (len(entries) + 1)
for name, entry in entries.items():
    names[entry['protocol_id'] + 1] = name.removeprefix('minecraft:')
Path('src/sound_data.inc').write_text(
    '/* Generated by tools/sounds.py; 1.19.4 registry SHA256 ' + hashlib.sha256(raw).hexdigest() + ' */\n'
    'static const char *const sound_names[] = {\n' + ''.join(json.dumps(n) + ',\n' for n in names) + '};\n')
